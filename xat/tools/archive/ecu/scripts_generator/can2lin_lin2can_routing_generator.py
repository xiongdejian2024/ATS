def write_sdk_to_pcan_module(sdk_list, pcan_path):
    with open(pcan_path, "a") as f:
        for sdk_func in sdk_list:
            f.write(sdk_func)


def create_test_file_dir_if_absent(test_file_dir):
    if os.path.isfile(test_file_dir):
        raise RuntimeError('directory "{}" is a file, not a directory!'.format(test_file_dir))

    if not os.path.isdir(test_file_dir):
        # mkdir() is for one layer directory, so we use makedirs() for multi-layer directories
        os.makedirs(test_file_dir)


def get_source_and_target_bus_info(signal=None):
    source_bus_info = dict()
    target_bus_info = dict()

    if signal:
        for key, value in signal.items():
            if "Source CAN Bus" in key or "Source LIN Bus" in key:
                source_bus_info['source_bus'] = value.strip()
            elif "Source Signal Name" in key:
                source_bus_info['source_sig_name'] = value.strip()
            elif "Source Signal Description" in key:
                source_bus_info['source_sig_desp'] = value.strip()
            elif "Source Message Name" in key:
                source_bus_info['source_msg_name'] = value.strip()
            elif "Source Message ID" in key:
                source_bus_info['source_msg_id'] = value.strip()
            elif value.upper() == 'X':
                target_bus_info[key] = {}
                target_bus_name = key.split('_')[0]

                target_bus_info[key]['target_sig_name'] = \
                    signal.get("{} Signal name".format(key)).strip()
                target_bus_info[key]['target_msg_name'] = \
                    signal.get("{} Message name".format(key)).strip()
                target_bus_info[key]['target_msg_id'] = \
                    signal.get("{} Message ID".format(key)).strip()
            else:
                continue
    else:
        raise Exception("Not able to get the source and target bus info due to no signal input")

    return source_bus_info, target_bus_info


