def generate_can2lin_lin2can_case(json_file_dir=None):
    cgw_all_msg_dict = dict()
    bgm_all_msg_dict = dict()

    if json_file_dir:
        filename_list = os.listdir(json_file_dir)
        filename_list.sort()

        for filename in filename_list:
            with open(os.path.join(json_file_dir, filename), 'r') as load_f:
                load_content = json.load(load_f)

            if args.project == "CGW":
                for veh_type in CGW_VEHICLE_TYPE:
                    if filename.startswith(veh_type):
                        cgw_all_msg_dict = get_all_msg_dict(cgw_all_msg_dict, load_content, veh_type, filename)

            elif args.project == "BGM":
                for veh_type in BGM_VEHICLE_TYPE:
                    if filename.startswith(veh_type):
                        bgm_all_msg_dict = get_all_msg_dict(bgm_all_msg_dict, load_content, veh_type, filename)

        write_test_cases_to_file(all_msg=cgw_all_msg_dict)
        write_test_cases_to_file(all_msg=bgm_all_msg_dict)
        # print(cgw_all_msg_dict.get("ES6") == cgw_all_msg_dict.get("ES8"))
        # print("cgw_all_msg_dict ES8: {}".format(cgw_all_msg_dict.get("ES8")))

    else:
        raise Exception("JSON file directory is not specified")


def get_all_msg_dict(all_msg_dict, load_content, veh_type, filename):
    # create dict key if none
    if not all_msg_dict.get(veh_type):
        all_msg_dict[veh_type] = {}

    # judge routing table and signal value
    if 'SIG_VALUE' not in filename:
        if not all_msg_dict[veh_type].get('routing_object'):
            all_msg_dict[veh_type]['routing_object'] = load_content
        elif all_msg_dict[veh_type].get('routing_object'):
            all_msg_dict[veh_type]['routing_object'].extend(load_content)
    else:
        if not all_msg_dict[veh_type].get('signal_value'):
            all_msg_dict[veh_type]['signal_value'] = load_content
        elif all_msg_dict[veh_type].get('signal_value'):
            all_msg_dict[veh_type]['signal_value'] = dict(all_msg_dict[veh_type]['signal_value'], **load_content)

    return all_msg_dict


