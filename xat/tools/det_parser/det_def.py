def paser_det_id(module, api_id, error_id):
    a = BswModule(module).name
    if not a:
        exit('Please Check Module {}'.format(a))
    mod = sys.modules[__name__]
    tc = getattr(mod, a)()
    api_name = tc.ApiId(api_id).name
    if not api_name:
        exit('Please Check ApiId')
    err_name = tc.ErrId(error_id).name
    if not api_name:
        exit('Please Check ErrId')

    return a, api_name, err_name


